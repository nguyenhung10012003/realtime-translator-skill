// Bundles the CLI into one self-contained file inside the skill, so installing the
// skill needs no `npm install`.
//
// application-loopback stays external: it's an optional Windows-only native addon,
// installed on demand by `scripts/setup.mjs --install-windows-capture`.
import { build } from 'esbuild'
import { chmodSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const skill = resolve(root, 'skills/realtime-translator')
const outfile = resolve(skill, 'scripts/translator.cjs')

mkdirSync(dirname(outfile), { recursive: true })

await build({
  entryPoints: [resolve(skill, 'src/cli/index.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  external: ['application-loopback'],
  banner: { js: '// GENERATED by scripts/build.mjs from src/. Do not edit by hand.' },
  logLevel: 'info',
})

chmodSync(outfile, 0o755)
